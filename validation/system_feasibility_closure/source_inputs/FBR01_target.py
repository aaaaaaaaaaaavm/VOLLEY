"""Finite-force retargeting of archived matched J2 point-mass campaigns.

Two constant inertial force arcs separated by a coast; actual mass flow and
parent/child recoil. Targets are archived, not generated by this targeter.
No physical engine, attitude/plume clearance or navigation rating is implied.
"""
from pathlib import Path
import argparse, csv, json, hashlib, time
import numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import root

HERE = Path(__file__).resolve().parent
INPUT = HERE/'inputs'
MU, RE, J2, ISP, G0 = 3.986004418e14, 6378137., 1.08262668e-3, 220., 9.80665
FINAL, PREP, GUARD = 90000., -900., 20.

def gravity(r):
    R = np.linalg.norm(r); q = (r[2]/R)**2
    return -MU*r/R**3 + 1.5*J2*MU*RE**2/R**5*r*np.array([5*q-1,5*q-1,5*q-3])

def arc(s, a, b, force=None, step=60., dense=False):
    if abs(a-b) < 1e-9: return np.array(s)
    force = np.zeros(3) if force is None else np.asarray(force)
    flow = np.linalg.norm(force)/(ISP*G0)
    def rhs(t, y):
        if len(y) == 6: return np.r_[y[3:6], gravity(y[:3])]
        return np.r_[y[3:6], gravity(y[:3])+force/y[6], -flow]
    result = solve_ivp(rhs, (a,b), s, method='DOP853', max_step=step,
                       rtol=2e-12, atol=1e-8, dense_output=dense)
    if not result.success: raise RuntimeError(result.message)
    return result if dense else result.y[:,-1]

def read_case(name):
    src = INPUT/(name+'_events.csv')
    rows = list(csv.DictReader(src.open()))
    def state(r,prefix=''):
        return np.array([float(r[prefix+k]) for k in ['rx','ry','rz','vx','vy','vz']])
    first = rows[0]
    shots = []
    for r in rows:
        if r['kind'] != 'shot': continue
        t = float(r['t_s']); target = state(r,'target_')
        desired = arc(target,FINAL,t)
        shots.append(dict(t=t,m=float(r['payload_kg']),
                          u=np.array([float(r[k]) for k in ['dx','dy','dz']]),
                          target=target,desired=desired,payload=int(r['payload'])))
    return dict(name=name,path=src,sha=hashlib.sha256(src.read_bytes()).hexdigest(),
                initial=state(first), mass=float(first['mass_before_kg']), shots=shots,
                host_target=state(first,'target_'))

def leg(s,a,b,target,fraction,shot,step):
    duration=b-a; d=duration*fraction
    times=[a,a+d,b-d,b]
    dt=duration
    # Linear double-integrator seed, then nonlinear six-state targeting.
    end0=arc(s,a,b,step=step)
    vtarget=target[3:6].copy()
    if shot is not None: vtarget -= (1-shot['m']/s[6])*shot['u']
    dr=target[:3]-end0[:3]; dv=vtarget-end0[3:6]
    mat=np.array([[d*(dt-d/2),d*d/2],[d,d]])/s[6]
    seed=np.linalg.solve(mat,np.stack([dr,dv])).reshape(6)
    def propagate(x):
        z=arc(s,a,times[1],x[:3],step)
        z=arc(z,times[1],times[2],step=step)
        return arc(z,times[2],b,x[3:],step)
    def residual(x):
        z=propagate(x)
        vgoal=target[3:6].copy()
        if shot is not None: vgoal -= (1-shot['m']/z[6])*shot['u']
        return np.r_[(z[:3]-target[:3])/dt,z[3:6]-vgoal]
    sol=root(residual,seed,method='hybr',options={'xtol':1e-9,'eps':1e-6})
    z=propagate(sol.x); res=residual(sol.x)
    good=np.linalg.norm(res[:3])*dt < .001 and np.linalg.norm(res[3:]) < 1e-6
    return dict(end=z,force=sol.x.reshape(2,3),times=times,
                position_residual_m=float(np.linalg.norm(res[:3])*dt),
                velocity_residual_m_s=float(np.linalg.norm(res[3:])),
                root_success=bool(sol.success),root_message=str(sol.message),
                evaluations=int(sol.nfev),targeting_pass=bool(good))

def run(name,fraction=.35,step=60.,force_limit=20.,fuel_override=None):
    case=read_case(name); start=time.monotonic()
    initial_fuel=float(name.split('_')[-1].removesuffix('kg'))
    s=np.r_[arc(case['initial'],0,PREP,step=step),case['mass']]
    if fuel_override is not None:
        s[6]+=fuel_override-initial_fuel; initial_fuel=fuel_override
    initial=s.copy(); now=PREP; fuel=initial_fuel
    legs=[]; events=[]; deliveries=[]; trajectory=[]
    def segment(a,b,F,label):
        nonlocal s
        if b-a<1e-9: return
        before=s.copy(); sol=arc(s,a,b,F,step,True); s=sol.y[:,-1]
        events.append(dict(kind='arc',start_s=a,end_s=b,force_N=list(F),
                           before=list(before),after=list(s),label=label))
        for t in np.linspace(a,b,max(2,int((b-a)/30)+1)):
            trajectory.append([float(t),*map(float,sol.sol(t))])
    for i,shot in enumerate(case['shots']+[None]):
        end=shot['t'] if shot is not None else 4200.
        target=shot['desired'] if shot is not None else arc(case['host_target'],FINAL,end,step=step)
        if now != PREP:
            segment(now,now+GUARD,np.zeros(3),'post_release_guard'); now+=GUARD
        found=leg(s,now,end,target,fraction,shot,step)
        legs.append({k:(v.tolist() if isinstance(v,np.ndarray) else v) for k,v in found.items() if k!='end'})
        if not found['targeting_pass']: break
        ts=found['times']; Fs=found['force']
        segment(ts[0],ts[1],Fs[0],'first_force_window')
        segment(ts[1],ts[2],np.zeros(3),'inter_window_coast')
        segment(ts[2],ts[3],Fs[1],'second_force_window')
        fuel=initial_fuel-(initial[6]-sum(x['m'] for x in case['shots'][:i])-s[6])
        if shot is not None:
            before=s.copy(); m=shot['m']; u=shot['u']
            child=s[:6].copy(); child[3:]+=(1-m/s[6])*u
            parent_v=s[3:6]-m/s[6]*u
            momentum=m*child[3:]+(s[6]-m)*parent_v-s[6]*s[3:6]
            terminal=arc(child,end,FINAL,step=step)
            deliveries.append(dict(payload=shot['payload'],release_s=end,
                 child_state=child.tolist(),target=shot['target'].tolist(),
                 terminal_state=terminal.tolist(),position_error_m=float(np.linalg.norm(terminal[:3]-shot['target'][:3])),
                 velocity_error_m_s=float(np.linalg.norm(terminal[3:]-shot['target'][3:])),
                 momentum_error_kg_m_s=float(np.linalg.norm(momentum))))
            s[3:6]=parent_v; s[6]-=m
            events.append(dict(kind='shot',start_s=end,end_s=end,payload=shot['payload'],
                               payload_mass_kg=m,u_m_s=u.tolist(),before=before.tolist(),after=s.tolist(),target=shot['target'].tolist()))
        now=end
    completed=len(deliveries)==len(case['shots']) and len(legs)==len(case['shots'])+1 and all(x['targeting_pass'] for x in legs)
    if completed: segment(now,FINAL,np.zeros(3),'final_host_coast')
    used=initial[6]-s[6]-sum(x['m'] for x in case['shots'][:len(deliveries)])
    peak=max((np.linalg.norm(F) for l in legs for F in l['force']),default=0.)
    report=dict(study='FBR-01',case=name,source_sha256=case['sha'],fraction=fraction,
                max_step_s=step,force_limit_N=force_limit,initial_fuel_kg=initial_fuel,
                initial_time_s=PREP,initial_state=initial.tolist(),final_time_s=FINAL,
                final_host_target=case['host_target'].tolist(),final_host_state=s.tolist(),
                legs=legs,events=events,deliveries=deliveries,completed_targeting=completed,
                fuel_used_kg=float(used),fuel_remaining_kg=float(initial_fuel-used),
                peak_force_N=float(peak),force_limit_pass=bool(peak<=force_limit),
                fuel_limit_pass=bool(used<=initial_fuel),
                reserve_exhaustion_policy='Any trajectory beyond the fuel budget is diagnostic only and infeasible; no continued operation is supported.',
                host_position_error_m=float(np.linalg.norm(s[:3]-case['host_target'][:3])) if completed else None,
                host_velocity_error_m_s=float(np.linalg.norm(s[3:6]-case['host_target'][3:])) if completed else None,
                elapsed_s=time.monotonic()-start,
                limitations=['Constant inertial resultant force and Isp220s are surrogate controls.',
                'Fixed-axis J2; no drag, higher gravity, Sun/Moon, hardware/nav/attitude/plume model.',
                'Point-centre instantaneous release; no physical custody/exit-envelope proof.',
                'Two-window policy is constructed, not a global fuel or service optimum.'])
    report['feasible_in_declared_model']=bool(completed and report['force_limit_pass'] and report['fuel_limit_pass'])
    out=HERE/'release'; out.mkdir(exist_ok=True)
    stem=f'{name}_f{fraction:g}_h{step:g}'+('' if fuel_override is None else f'_fuel{fuel_override:g}')
    (out/(stem+'.json')).write_text(json.dumps(report,indent=2)+'\n')
    np.savetxt(out/(stem+'_trajectory.csv'),trajectory,delimiter=',',header='t_s,x_m,y_m,z_m,vx_m_s,vy_m_s,vz_m_s,mass_kg',comments='')
    print(json.dumps({k:report[k] for k in ['case','completed_targeting','feasible_in_declared_model','peak_force_N','fuel_used_kg','host_position_error_m','elapsed_s']}),flush=True)
    return report

if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('case');p.add_argument('--fraction',type=float,default=.35)
    p.add_argument('--step',type=float,default=60);p.add_argument('--force-limit',type=float,default=20)
    p.add_argument('--fuel',type=float);a=p.parse_args()
    run(a.case,a.fraction,a.step,a.force_limit,a.fuel)
