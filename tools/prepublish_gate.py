#!/usr/bin/env python3
"""Block common public-release defects in changed files before a push.

Run: python3 tools/prepublish_gate.py --base <published-commit>
Use --all for a full-tree release candidate. This is an automated gate, not an
engineering sign-off; see PUBLICATION_POLICY.md for the required human checks.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote


ROOT = Path(__file__).resolve().parents[1]
TEXT = {".md", ".txt", ".tex", ".html", ".htm", ".py", ".js", ".cjs", ".json", ".yml", ".yaml", ".csv", ".sh", ".svg", ".scad", ".css"}
LINK = re.compile(r"!?\[[^\]]*\]\((<[^>]+>|[^)]+)\)|<img\b[^>]*\bsrc=['\"]([^'\"]+)", re.I)
SECRET = [
    (re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"), "private key"),
    (re.compile(r"\bgh[pousr]_[A-Za-z0-9_]{25,}\b"), "GitHub token"),
    (re.compile(r"\bgithub_pat_[A-Za-z0-9_]{25,}\b"), "GitHub token"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "AWS access key"),
]
FORBIDDEN_NAMES = ("GUIDE_DECISION_REQUEST", "INTERNAL_HANDOFF", "PRIVATE_REVIEW_DRAFT")


def git(*args: str) -> bytes:
    return subprocess.check_output(["git", *args], cwd=ROOT, stderr=subprocess.DEVNULL)


def changed_paths(base: str | None, all_files: bool) -> list[str]:
    if all_files:
        raw = git("ls-files", "-z")
    else:
        if not base:
            raise ValueError("pass --base <published commit> or --all")
        raw = git("diff", "--name-only", "--diff-filter=ACMR", "-z", base, "HEAD")
        # A developer may run the gate before committing; include staged and working edits.
        raw += git("diff", "--name-only", "--diff-filter=ACMR", "-z", "HEAD")
    return sorted(set(p.decode() for p in raw.split(b"\0") if p))


def markdown_links(path: Path, rel: str, errors: list[str]) -> None:
    fenced = False
    for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
            continue
        if fenced:
            continue
        for match in LINK.finditer(line):
            raw = next((g for g in match.groups() if g), "").strip("<>")
            target = unquote(raw.split("#", 1)[0].split("?", 1)[0])
            if not target or target.startswith(("http:", "https:", "mailto:", "data:", "//", "#")):
                continue
            # Literal templates and shell examples are not filesystem links.
            if any(mark in target for mark in ("{", "}", "$", "*", "<", ">")):
                continue
            resolved = (path.parent / target).resolve()
            if not resolved.is_relative_to(ROOT.resolve()) or not resolved.exists():
                errors.append(f"{rel}:{number}: missing or external local link: {target}")


def check(path_name: str, errors: list[str]) -> None:
    path = ROOT / path_name
    if not path.is_file():
        return
    if path.suffix.lower() == ".fcbak":
        errors.append(f"{path_name}: uncontrolled native CAD backup is not publishable")
        return
    if any(marker in path_name.upper() for marker in FORBIDDEN_NAMES):
        errors.append(f"{path_name}: internal draft filename is not publishable")
    if path.stat().st_size > 30_000_000:
        errors.append(f"{path_name}: file exceeds 30 MB; review distribution and provenance")
        return
    suffix = path.suffix.lower()
    if suffix in TEXT:
        value = path.read_text(encoding="utf-8", errors="replace")
        for pattern, label in SECRET:
            if pattern.search(value):
                errors.append(f"{path_name}: possible {label}")
        # Prevent accidental assistant-generated footer text on a public page.
        if re.search(r"generated by\s+(?:claude|chatgpt|codex)(?:\s+code)?", value, re.I):
            errors.append(f"{path_name}: unreviewed tool footer")
        if suffix == ".md":
            markdown_links(path, path_name, errors)
    elif suffix == ".pdf":
        data = path.read_bytes()
        if not data.startswith(b"%PDF-") or b"%%EOF" not in data[-2048:]:
            errors.append(f"{path_name}: incomplete PDF")
    elif suffix in {".step", ".stp"}:
        data = path.read_bytes()
        if not data.lstrip().startswith(b"ISO-10303-21;") or b"END-ISO-10303-21;" not in data[-1024:]:
            errors.append(f"{path_name}: incomplete STEP exchange file")
    elif suffix == ".png" and not path.read_bytes().startswith(b"\x89PNG\r\n\x1a\n"):
        errors.append(f"{path_name}: invalid PNG signature")
    elif suffix in {".jpg", ".jpeg"} and not path.read_bytes().startswith(b"\xff\xd8\xff"):
        errors.append(f"{path_name}: invalid JPEG signature")


def check_evidence_tracking(errors: list[str]) -> None:
    """Every file in a current captured-study manifest must enter the Git payload."""
    import json
    tracked = set(git("ls-files", "-z").decode().split("\0"))
    for name in ["validation/native_campaign_review/MANIFEST.json",
                 "experiments/native-campaign-review/MANIFEST.json",
                 "validation/captive_transfer_review/MANIFEST.json",
                 "validation/replenishment_feasibility/MANIFEST.json",
                 "experiments/captive-transfer-review/MANIFEST.json",
                 "experiments/replenishment-feasibility/MANIFEST.json"]:
        manifest = ROOT / name
        if not manifest.is_file():
            continue
        for relative in ["MANIFEST.json", *json.loads(manifest.read_text())["files"]]:
            path = (manifest.parent / relative).resolve()
            if path.suffix == ".FCBak" or path.name == "spooles.out":
                errors.append(f"{name}: uncontrolled backup/scratch artifact in release: {relative}")
            if not path.is_relative_to(ROOT.resolve()):
                errors.append(f"{name}: evidence path escapes repository: {relative}")
            elif path.relative_to(ROOT).as_posix() not in tracked:
                errors.append(f"{name}: required evidence is absent from Git index: {relative}")


def check_outer_hashes(errors: list[str]) -> None:
    """Keep the academic outer identity ledger synchronized with inner records."""
    import hashlib
    manifest = ROOT / "ARTIFACT_MANIFEST.sha256"
    if not manifest.is_file():
        return
    for line in manifest.read_text().splitlines():
        if not line.strip():
            continue
        expected, relative = line.split("  ", 1)
        path = (ROOT / relative).resolve()
        if not path.is_relative_to(ROOT.resolve()) or not path.is_file():
            errors.append(f"outer manifest missing or external artifact: {relative}")
        elif hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            errors.append(f"outer manifest checksum stale: {relative}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", help="published commit to compare to HEAD")
    parser.add_argument("--all", action="store_true", help="scan every tracked file for a release candidate")
    args = parser.parse_args()
    try:
        paths = changed_paths(args.base, args.all)
    except (ValueError, subprocess.CalledProcessError) as exc:
        print(f"FAIL: cannot determine publication set: {exc}", file=sys.stderr)
        return 2
    errors: list[str] = []
    check_evidence_tracking(errors)
    check_outer_hashes(errors)
    for name in paths:
        check(name, errors)
    if errors:
        print(f"FAIL: prepublication gate found {len(errors)} issue(s) in {len(paths)} files:")
        for issue in errors:
            print("  " + issue)
        return 1
    print(f"PASS: prepublication gate checked {len(paths)} changed/tracked files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
